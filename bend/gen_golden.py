"""Write bend/fixtures/golden.json: byte-exact frames from the Python protocol, the reference the Bend port must match.

Usage: python3 bend/gen_golden.py      (run from the repo root)
Only app->panel frames and synthetic data are used: no replies or identifiers from real captures.
"""
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import protocol as P

TS = 1792878202
RGB = bytes((x * 3 + y * 5 + c * 7) & 0xFF for y in range(64) for x in range(64) for c in range(3))  # deterministic gradient


def h(b: bytes) -> str:
    return b.hex()


packed = P.pack_image(RGB)
key = P.make_key(7, packed, TS)
bodies = P.upload_bodies(6, packed, key, TS)
out = {
    "checksum": [{"body": h(b), "frame": h(P.build(9, b))} for b in (b"\x03\x04\x00", b"\x02\x08\x02\x00\x00")],
    "frames": {
        "device_info_41": h(P.device_info(41)),
        "show_image_11_slot3": h(P.show_image(11, 3)),
        "query_power": h(P.query(50, 0x04)),
        "power_on": h(P.set_power(51, True)),
        "power_off": h(P.set_power(52, False)),
        "rotation_2": h(P.set_rotation(53, 2)),
        "brightness_7": h(P.set_brightness(54, 7)),
        # seen in a real capture (app->panel): delete of slot 0, seq 0x0c
        "delete_slot0_seq12_captured": "aa55ffff0a000c00c10208020000e003",
        "delete_slot0_seq12": h(P.delete_slot(12, 0)),
        "delete_slot6_seq13": h(P.delete_slot(13, 6)),
    },
    "reassembly": {  # one frame fed in uneven chunks, then two frames glued together
        "frame": h(P.build(5, bytes([0x83, 0x35, 0x81, 0xD2]) + bytes(210))),
        "splits": [[180], [1, 5, 100], [7] * 31],
    },
    "image": {
        "rgb_sha256": hashlib.sha256(RGB).hexdigest(),
        "packed_sha256": hashlib.sha256(packed).hexdigest(),
        "packed_len": len(packed),
        "gamma_table_sha256": hashlib.sha256(bytes(int(256 * ((a + 0.5) / 256) ** P.GAMMA - 0.5) for a in range(256))).hexdigest(),
    },
    "upload": {
        "slot": 6, "ts": TS, "key": h(key),
        "frames": [h(P.build(100 + i, b)) for i, b in enumerate(bodies)],
    },
    "tlv_len": {str(n): h(P._len_tlv(n)) for n in (0, 5, 127, 128, 783, 960)},
}
Path(__file__).with_name("fixtures").joinpath("golden.json").write_text(json.dumps(out, indent=1) + "\n")
print(f"{len(out['upload']['frames'])} upload frames, packed image {len(packed)} bytes")


# --- the same vectors as Bend data, for bend/test.bend (hex text; the test decodes it with Bytes.from_hex) ---
def small(frame: bytes) -> bool:
    return len(frame) <= 260


cases = [(name, bytes.fromhex(hx)) for name, hx in out["frames"].items()]
cases += [(f"upload_frame_{i}", bytes.fromhex(hx)) for i, hx in enumerate(out["upload"]["frames"]) if small(bytes.fromhex(hx))]


def split(data: bytes, sizes: list[int]) -> list[bytes]:
    out_, pos, i = [], 0, 0
    while pos < len(data):
        n = sizes[i % len(sizes)]
        out_.append(data[pos:pos + n]); pos += n; i += 1
    return out_


def strings(items: list[bytes]) -> str:
    return "{[" + ", ".join(f'"{b.hex()}"' for b in items) + "] : List<&2, String>}"


big = bytes.fromhex(out["reassembly"]["frame"])
second = P.build(6, bytes([0x83, 0x04, 0x01, 0x01]), P.DIR_PANEL)
splits = [(f"one_frame_split_{k}", split(big, sizes), [big]) for k, sizes in enumerate(out["reassembly"]["splits"])]
splits.append(("two_frames_one_chunk", [big + second], [big, second]))
splits.append(("two_frames_uneven", split(big + second, [50, 3, 200]), [big, second]))
splits.append(("tail_kept_until_complete", [big[:100]], []))
splits.append(("torn_frame_dropped_at_new_magic", [big[:100], second], [second]))
splits.append(("short_chunks_under_magic_len", split(second, [1, 2, 1]) , [second]))

for name, chunks, frames in splits:  # the expectations must be what protocol.Reassembler really does
    ra, got = P.Reassembler(), []
    for c in chunks:
        got += ra.feed(c)
    assert got == frames, name

keys = []
for id_pro, packed, ts in ((7, bytes(range(20)), 1792878202), (1, b"", 0), (16, b"YSTP01" + bytes(30), 4294967295), (255, bytes([255]) * 5, 1)):
    keys.append((id_pro, packed, ts, P.make_key(id_pro, packed, ts)))

lines = ["# Generated by bend/gen_golden.py from protocol.py. Do not edit.", "import Base", "",
         "type Case is Data:", "  Case{name: String, seq: U32, dir: U32, body: String, frame: String}", "",
         "type Split is Data:", "  Split{name: String, chunks: List<&2, String>, frames: List<&2, String>}", "",
         "type KeyCase is Data:", "  KeyCase{id_pro: U32, packed: String, ts: U32, key: String}", "",
         "def Golden.cases() -> List<&2, Case>:", "  ["]
rows = []
for name, frame in cases:
    p_ = P.parse(frame)
    rows.append(f'    Case{{"{name}", {p_["seq"]}, {p_["dir"]}, "{p_["body"].hex()}", "{frame.hex()}"}}')
lines.append(",\n".join(rows))
lines += ["  ]", "", "def Golden.splits() -> List<&2, Split>:", "  ["]
rows = [f'    Split{{"{n}", {strings(c)}, {strings(f)}}}' for n, c, f in splits]
lines.append(",\n".join(rows))
lines += ["  ]", "", "def Golden.keys() -> List<&2, KeyCase>:", "  ["]
lines.append(",\n".join(f'    KeyCase{{{i}, "{pk.hex()}", {t}, "{k.hex()}"}}' for i, pk, t, k in keys))
lines += ["  ]", ""]
Path(__file__).with_name("golden.bend").write_text("\n".join(lines))
print(f"{len(cases)} frame cases, {len(splits)} reassembly cases")
